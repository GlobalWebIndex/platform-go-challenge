package favourites

import (
	"context"
	"errors"
)

// Domain-level validation errors for service inputs.
var (
	ErrUserIDRequired      = errors.New("userID is required")
	ErrAssetIDRequired     = errors.New("assetID is required")
	ErrDescriptionRequired = errors.New("description is required")
)

// Service defines the business operations for managing favourites.
type Service interface {
	// ListUserFavourites returns all favourites for a user, optionally filtered by type.
	ListUserFavourites(ctx context.Context, userID string, filter ListFilter) ([]FavouriteEntry, error)

	// AddFavourite creates an asset inline and marks it as a favourite for the user.
	// Asset IDs are auto-generated; callers must not provide an ID.
	AddFavourite(ctx context.Context, userID string, asset Asset) (FavouriteEntry, error)

	// RemoveFavourite removes the favourite link between user and asset.
	// Idempotent: does not fail if the favourite does not exist.
	RemoveFavourite(ctx context.Context, userID, assetID string) error

	// EditFavouriteDescription updates the asset description for a favourite.
	// Returns ErrFavouriteNotFound if the (user, asset) pair does not exist.
	EditFavouriteDescription(ctx context.Context, userID, assetID, description string) (FavouriteEntry, error)
}

// service is the concrete implementation behind the Service interface.
// It uses a Repository for storage concerns.
type service struct {
	repo Repository
}

// NewService constructs a new favourites Service. Panics if repo is nil.
func NewService(repo Repository) Service {
	if repo == nil {
		panic("favourites: nil Repository passed to NewService")
	}

	return &service{
		repo: repo,
	}
}

// ListUserFavourites returns all favourites for the given user, optionally filtered by type.
func (s *service) ListUserFavourites(
	ctx context.Context,
	userID string,
	filter ListFilter,
) ([]FavouriteEntry, error) {
	if userID == "" {
		return nil, ErrUserIDRequired
	}

	return s.repo.ListFavourites(ctx, userID, filter)
}

// AddFavourite creates an asset inline and adds it to the user's favourites.
// userID must be non-empty. asset.ID must be empty (generated by repository).
//
// Note: Duplicate favourites are impossible by design. Each call creates a new asset
// with a unique UUID, so the same asset content can be favourited multiple times as
// separate assets with different IDs.
func (s *service) AddFavourite(
	ctx context.Context,
	userID string,
	asset Asset,
) (FavouriteEntry, error) {
	if userID == "" {
		return FavouriteEntry{}, ErrUserIDRequired
	}

	// Enforce asset.ID is empty at service layer (defense in depth).
	if asset.ID != "" {
		return FavouriteEntry{}, ErrInvalidAssetPayload
	}

	entry, err := s.repo.CreateFavourite(ctx, userID, asset)
	if err != nil {
		return FavouriteEntry{}, err
	}

	return entry, nil
}

// RemoveFavourite removes the favourite link. Idempotent.
func (s *service) RemoveFavourite(
	ctx context.Context,
	userID, assetID string,
) error {
	if userID == "" {
		return ErrUserIDRequired
	}
	if assetID == "" {
		return ErrAssetIDRequired
	}

	return s.repo.RemoveFavourite(ctx, userID, assetID)
}

// EditFavouriteDescription updates the asset description if the user has it as a favourite.
// Returns ErrFavouriteNotFound if the favourite doesn't exist.
func (s *service) EditFavouriteDescription(
	ctx context.Context,
	userID, assetID, description string,
) (FavouriteEntry, error) {
	if userID == "" {
		return FavouriteEntry{}, ErrUserIDRequired
	}
	if assetID == "" {
		return FavouriteEntry{}, ErrAssetIDRequired
	}
	if description == "" {
		return FavouriteEntry{}, ErrDescriptionRequired
	}

	entry, err := s.repo.UpdateDescriptionForUser(ctx, userID, assetID, description)
	if err != nil {
		return FavouriteEntry{}, err
	}

	return entry, nil
}
